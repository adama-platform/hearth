  @Test
  public void aVersionOneDatabaseUpgradesToVersionTwoInPlace() throws Exception {
    // exactly the shape shipped before approval and roles existed: no approved_at, no signup
    // columns in the middle of emails, and no roles table at all
    run("CREATE TABLE emails ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,"
        + "email VARCHAR(320) NOT NULL,"
        + "password_hash VARCHAR(512),"
        + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "verified_at TIMESTAMP,"
        + "last_login_at TIMESTAMP,"
        + "sessions_valid_after TIMESTAMP,"
        + "failed_attempts INTEGER NOT NULL DEFAULT 0,"
        + "locked_until TIMESTAMP,"
        + "disabled BOOLEAN NOT NULL DEFAULT FALSE)");
    run("INSERT INTO emails (email, verified_at) VALUES ('early@example.com', CURRENT_TIMESTAMP)");
    upgrade();

    assertEquals("the upgraded table should be shaped exactly like a fresh one",
        declaredOrder(Schema.EMAILS_TABLE), columnOrder(Schema.EMAILS));
    assertEquals(declaredOrder(Schema.ROLES_TABLE), columnOrder(Schema.ROLES));
    try (Connection connection = connect();
         Statement statement = connection.createStatement();
         ResultSet rows = statement.executeQuery(
             "SELECT email, approved_at, signup_events FROM emails")) {
      assertTrue(rows.next());
      assertEquals("the row from before the upgrade survives", "early@example.com", rows.getString(1));
      assertEquals("and is unapproved, which is the safe reading of 'we did not ask'", null, rows.getTimestamp(2));
      assertEquals("with a default rather than a null", 0, rows.getInt(3));
    }
  }

  @Test
  public void aCompositeUniqueIsAddedToAnExistingTable() throws Exception {
    run("CREATE TABLE roles ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,"
        + "user_id BIGINT NOT NULL,"
        + "role_name VARCHAR(64) NOT NULL,"
        + "granted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "granted_by BIGINT)");
    upgrade();
    run("INSERT INTO roles (user_id, role_name) VALUES (1, 'admin')");
    try {
      run("INSERT INTO roles (user_id, role_name) VALUES (1, 'admin')");
      fail("a second identical grant should be refused by the constraint");
    } catch (SQLException expected) {
      assertTrue(expected.getMessage(), expected.getMessage().toLowerCase(Locale.ROOT).contains("unique"));
    }
  }

  @Test
  public void indexesAreCreated() throws Exception {
    upgrade();
    try (Connection connection = connect();
         Statement statement = connection.createStatement();
         ResultSet rows = statement.executeQuery(
             "SELECT index_name FROM information_schema.indexes WHERE table_schema = 'PUBLIC'")) {
      ArrayList<String> names = new ArrayList<>();
      while (rows.next()) {
        names.add(rows.getString(1).toLowerCase(Locale.ROOT));
      }
      assertTrue(names.toString(), names.contains("idx_sessions_user"));
      assertTrue(names.toString(), names.contains("idx_emails_email"));
    }
  }

  @Test
  public void aStoreOpensAuditsAndReports() throws Exception {
    try (Store store = Store.open(dir, "example.com", Verbose.OFF)) {
      assertNotNull(store.audit());
      assertFalse(store.audit().existed());
      assertTrue(store.audit().changed());
      assertEquals("created, schema v" + Schema.VERSION, store.audit().summary());
    }
    try (Store store = Store.open(dir, "example.com", Verbose.OFF)) {
      assertTrue(store.audit().existed());
      assertFalse(store.audit().changed());
      assertTrue(store.audit().summary().contains("already current"));
    }
  }
