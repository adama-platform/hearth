  // ---- creating from nothing ---------------------------------------------------------------

  @Test
  public void anEmptyDatabaseGetsEveryTable() throws Exception {
    upgrade();
    assertEquals(declaredOrder(Schema.EMAILS_TABLE), columnOrder(Schema.EMAILS));
    assertEquals(declaredOrder(Schema.SESSIONS_TABLE), columnOrder(Schema.SESSIONS));
    assertEquals(declaredOrder(Schema.META_TABLE), columnOrder(Schema.META));
  }

  @Test
  public void h2OwnSessionsViewDoesNotLookLikeOurTable() throws Exception {
    // H2 ships INFORMATION_SCHEMA.SESSIONS; an unscoped metadata lookup finds it and the upgrader
    // then tries to ALTER a table that was never created
    upgrade();
    assertEquals(declaredOrder(Schema.SESSIONS_TABLE), columnOrder(Schema.SESSIONS));
  }

  @Test
  public void upgradingTwiceChangesNothing() throws Exception {
    upgrade();
    try (Connection connection = connect()) {
      SchemaUpgrader second = new SchemaUpgrader(Verbose.OFF);
      second.upgrade(connection, "test");
      assertTrue("a current database should need no DDL, got: " + second.applied(), second.applied().isEmpty());
      assertTrue(second.notes().isEmpty());
    }
  }

  @Test
  public void theVersionIsRecorded() throws Exception {
    upgrade();
    try (Connection connection = connect()) {
      assertEquals(Integer.toString(Schema.VERSION), SchemaUpgrader.storedVersion(connection));
    }
  }

  // ---- adding columns in the right place ---------------------------------------------------

  @Test
  public void aColumnMissingFromTheMiddleIsPutBackInPlace() throws Exception {
    // an older release without sessions_valid_after, which sits between last_login_at and
    // failed_attempts; a naive ADD COLUMN would put it on the end
    run("CREATE TABLE emails ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,"
        + "email VARCHAR(320) NOT NULL,"
        + "password_hash VARCHAR(512),"
        + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "verified_at TIMESTAMP,"
        + "last_login_at TIMESTAMP,"
        + "failed_attempts INTEGER NOT NULL DEFAULT 0,"
        + "locked_until TIMESTAMP,"
        + "disabled BOOLEAN NOT NULL DEFAULT FALSE)");
    upgrade();
    assertEquals("the upgraded table should be shaped exactly like a fresh one",
        declaredOrder(Schema.EMAILS_TABLE), columnOrder(Schema.EMAILS));
  }

  @Test
  public void severalMissingColumnsInARowLandInOrder() throws Exception {
    // three consecutive columns absent; each has to anchor against something that exists
    run("CREATE TABLE emails ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,"
        + "email VARCHAR(320) NOT NULL,"
        + "password_hash VARCHAR(512),"
        + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "failed_attempts INTEGER NOT NULL DEFAULT 0,"
        + "locked_until TIMESTAMP,"
        + "disabled BOOLEAN NOT NULL DEFAULT FALSE)");
    upgrade();
    assertEquals(declaredOrder(Schema.EMAILS_TABLE), columnOrder(Schema.EMAILS));
  }

  @Test
  public void aColumnMissingFromTheEndIsAppended() throws Exception {
    run("CREATE TABLE sessions ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,"
        + "token_hash VARCHAR(64) NOT NULL,"
        + "user_id BIGINT NOT NULL,"
        + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "last_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "expires_at TIMESTAMP,"
        + "revoked_at TIMESTAMP,"
        + "ip VARCHAR(64))");
    upgrade();
    assertEquals(declaredOrder(Schema.SESSIONS_TABLE), columnOrder(Schema.SESSIONS));
  }

  @Test
  public void existingRowsSurviveAnUpgrade() throws Exception {
    run("CREATE TABLE emails ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,"
        + "email VARCHAR(320) NOT NULL,"
        + "password_hash VARCHAR(512),"
        + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "verified_at TIMESTAMP,"
        + "last_login_at TIMESTAMP,"
        + "failed_attempts INTEGER NOT NULL DEFAULT 0,"
        + "locked_until TIMESTAMP,"
        + "disabled BOOLEAN NOT NULL DEFAULT FALSE)");
    run("INSERT INTO emails (email) VALUES ('somebody@example.com')");
    upgrade();
    try (Connection connection = connect();
         Statement statement = connection.createStatement();
         ResultSet rows = statement.executeQuery("SELECT email, sessions_valid_after FROM emails")) {
      assertTrue(rows.next());
      assertEquals("somebody@example.com", rows.getString(1));
      // the new column exists and is null for the row that predates it
      assertEquals(null, rows.getTimestamp(2));
      assertFalse(rows.next());
    }
  }

  @Test
  public void theDdlIsReportedForTheAudit() throws Exception {
    run("CREATE TABLE sessions ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,"
        + "token_hash VARCHAR(64) NOT NULL,"
        + "user_id BIGINT NOT NULL,"
        + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "last_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
        + "expires_at TIMESTAMP,"
        + "revoked_at TIMESTAMP,"
        + "user_agent VARCHAR(256))");
    try (Connection connection = connect()) {
      SchemaUpgrader upgrader = new SchemaUpgrader(Verbose.OFF);
      upgrader.upgrade(connection, "test");
      String ddl = String.join("\n", upgrader.applied());
      assertTrue(ddl, ddl.contains("ALTER TABLE sessions ADD COLUMN ip VARCHAR(64) BEFORE user_agent"));
    }
  }

  // ---- what it refuses to do ---------------------------------------------------------------

  @Test
  public void anExtraColumnIsLeftAloneAndReported() throws Exception {
    upgrade();
    run("ALTER TABLE emails ADD COLUMN nickname VARCHAR(64)");
    try (Connection connection = connect()) {
      SchemaUpgrader upgrader = new SchemaUpgrader(Verbose.OFF);
      upgrader.upgrade(connection, "test");
      assertTrue(upgrader.applied().isEmpty());
      assertEquals(1, upgrader.notes().size());
      assertTrue(upgrader.notes().get(0).contains("nickname"));
    }
    // still there; we do not drop what we did not create
    assertTrue(columnOrder(Schema.EMAILS).contains("nickname"));
  }

  @Test
  public void aChangedTypeIsFatal() throws Exception {
    run("CREATE TABLE emails ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,"
        + "email VARCHAR(64) NOT NULL)");
    try {
      upgrade();
      fail("expected a refusal");
    } catch (SchemaException ex) {
      assertTrue(ex.getMessage(), ex.getMessage().contains("emails.email"));
      assertTrue(ex.getMessage(), ex.getMessage().contains("will not change a column's type"));
    }
  }

  @Test
  public void aNotNullColumnWithoutADefaultIsRefusedAtDeclarationTime() {
    // this is a bug in Schema.java, caught before it can meet a populated table
    try {
      Column.of("late", "VARCHAR(10)").notNull().alterDdl();
      fail("expected a refusal");
    } catch (SchemaException ex) {
      assertTrue(ex.getMessage(), ex.getMessage().contains("NOT NULL with no default"));
    }
  }

  @Test
  public void addingANotNullColumnWithoutADefaultFailsWithAClearMessage() throws Exception {
    // a hand-edited or half-migrated database missing a founding column. There is no correct value
    // to backfill, so the refusal has to name the column rather than surfacing as raw SQL.
    run("CREATE TABLE emails ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,"
        + "password_hash VARCHAR(512))");
    try {
      upgrade();
      fail("expected a refusal");
    } catch (SchemaException ex) {
      assertTrue(ex.getMessage(), ex.getMessage().contains("'email' is NOT NULL with no default"));
      assertTrue(ex.getMessage(), ex.getMessage().contains("give it a default in the schema"));
    }
  }

  @Test
  public void everyColumnAddedAfterTheFoundingSetIsAddable() throws Exception {
    // the founding columns of each table only ever appear inside CREATE TABLE; everything declared
    // after them has to survive being added to a populated table, or the schema stops upgrading
    for (Table table : Schema.TABLES) {
      for (Column column : table.columns) {
        if (FOUNDING.contains(table.name + "." + column.name)) {
          continue;
        }
        column.alterDdl();
      }
    }
  }

